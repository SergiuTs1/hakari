/**
 * Поточний мікросезон.
 * @returns {{name: string}}
 */
export function currentKou(date = new Date()) {
  const p = n => String(n).padStart(2, '0');
  const md = `${p(date.getMonth() + 1)}-${p(date.getDate())}`;

  // останній відрізок, що вже почався; список впорядкований від 01-01
  let found = KOU[KOU.length - 1];
  for (const k of KOU) {
    if (k[0] <= md) found = k;
    else break;
  }
  return { name: found[1] };
}
